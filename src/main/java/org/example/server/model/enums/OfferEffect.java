package org.example.server.model.enums;

/**
 * Effects granted by the offer track tiles.
 */
public enum OfferEffect {
    /** Gain food. */
    FOOD,
    /** Down effect. */
    D,
    /** Up effect. */
    U,
    /** Double down effect. */
    DD,
    /** Down then up effect. */
    DU,
    /** Double up effect. */
    UU,
    /** Down then double up effect. */
    DUU
}